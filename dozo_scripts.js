// ============================================================
// 判定・生成関数
// ============================================================

// 危機判定
function checkCrisis(text) {
  return CRISIS_WORDS.some(w => text.includes(w));
}

// テンション判定
function detectTension(text) {
  for (const word of TENSION_KEYWORDS.low) {
    if (text.includes(word)) return "low";
  }
  for (const word of TENSION_KEYWORDS.high) {
    if (text.includes(word)) return "high";
  }
  return "mid";
}

// ランダム選択
function pick(arr) {
  return arr[Math.floor(Math.random() * arr.length)];
}

// 危機返答生成
function generateCrisisResponse(character) {
  return pick(CRISIS_SCRIPTS[character]);
}

// 通常返答生成
function generateResponse(character, text) {
  const tension = detectTension(text);
  const pool = SCRIPTS[character][tension];
  return [
    pick(pool.intro),
    pick(pool.reaction),
    pick(pool.comeback),
    pick(pool.ending),
  ].join("\n\n");
}
