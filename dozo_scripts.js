// ============================================================
// ユーティリティ
// ============================================================
function pick(arr) {
  return arr[Math.floor(Math.random() * arr.length)];
}

function checkCrisis(text) {
  return CRISIS_WORDS.some(w => text.includes(w));
}

function generateResponse(character, categoryId) {
  const s = SCRIPTS[character];
  const intro       = pick(s.intro);
  const categoryLine = s.category_line[categoryId] || pick(Object.values(s.category_line));
  const reaction    = pick(s.reaction);
  const ending      = pick(s.ending);
  return [intro, categoryLine, reaction, ending].join("\n\n");
}

function generateCrisisResponse(character) {
  return pick(CRISIS_SCRIPTS[character]);
}

// ============================================================
// localStorage 保存
// ============================================================
function saveLog({ character, emotion_category, user_message, response, reaction }) {
  const logs = JSON.parse(localStorage.getItem('dozo_logs') || '[]');
  logs.push({
    character,
    emotion_category,
    user_message,
    response,
    reaction,
    timestamp: new Date().toISOString(),
  });
  localStorage.setItem('dozo_logs', JSON.stringify(logs));
}
